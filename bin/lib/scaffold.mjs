/** The surface a product path rides with: apps/web/** and tests/** (the Playwright workspace) with web, apps/mobile/** with mobile; null elsewhere. */
export function surfaceOfPath(rel) {
  if (rel.startsWith("apps/web/") || rel.startsWith("tests/")) return "web";
  if (rel.startsWith("apps/mobile/")) return "mobile";
  return null;
}

/**
 * One rule for everything a module aims at a surface's tree: when that surface is not selected the
 * contribution is skipped, silently for a copy and with a summary line for a package fragment or an
 * env fragment — never an error. Returns the unselected surface, or null when the path is in play.
 */
const unselectedSurface = (rel, manifest) => {
  const s = surfaceOfPath(rel);
  return s && !manifest.surfaces.includes(s) ? s : null;
};

function shouldCopy(rel, layer, manifest) {
  const base = path.posix.basename(rel);
  if (base === ENV_FRAGMENT) return false; // merged into the .env.example beside it, at any depth
  if (base === AGENTS_FRAGMENT && path.posix.dirname(rel) === ".") return false; // merged into AGENTS.md
  if (layer.kind !== "module" && LAYER_META_FILES.includes(rel)) return false; // the layer's own manifest
  if (layer.kind === "module" && unselectedSurface(rel, manifest)) return false;
  return true;
}

function buildCopyPlan(layers, manifest, placeholders) {
  const plan = new Map();
  const put = (rel, entry) => plan.set(rel, entry);
  for (const layer of layers) {
    for (const f of walk(layer.filesDir)) {
      if (!shouldCopy(f.rel, layer, manifest)) continue;
      if (f.kind === "symlink") {
        put(f.rel, { kind: "symlink", source: layer.id, target: fs.readlinkSync(f.abs) });
        continue;
      }
      const raw = fs.readFileSync(f.abs);
      const mode = fs.statSync(f.abs).mode & 0o777;
      const content = isTextBuffer(raw, f.rel) ? Buffer.from(substitute(raw.toString("utf8"), placeholders)) : raw;
      put(f.rel, { kind: "copy", source: layer.id, content, mode });
    }
    if (layer.meta.docs) {
      const src = path.join(layer.dir, layer.meta.docs);
      if (!exists(src)) fail(`module "${layer.id}" declares docs "${layer.meta.docs}" but ${src} does not exist`);
      const text = substitute(fs.readFileSync(src, "utf8"), placeholders);
      put(layer.meta.docs, { kind: "copy", source: layer.id, content: Buffer.from(text), mode: 0o644 });
    }
  }
  return plan;
}

