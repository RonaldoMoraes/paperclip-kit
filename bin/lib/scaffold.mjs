const LAYER_META_FILES = ["module.json", "surface.json"]; // surface.json is the alias surfaces use

function readLayerMeta(dir, id, kitDir) {
  const metaPath = LAYER_META_FILES.map((f) => path.join(dir, f)).find(exists);
  if (!metaPath) return { id };
  const meta = readJson(metaPath);
  const schema = readJson(path.join(kitDir, "docs/module.schema.json"));
  const errors = validateSchema(schema, meta);
  if (errors.length) fail(`${path.relative(kitDir, metaPath)} is invalid:\n  - ${errors.join("\n  - ")}`);
  if (meta.id !== id) fail(`${path.relative(kitDir, metaPath)}: "id" is "${meta.id}" but the directory is "${id}"`);
  return meta;
}

/** base and surfaces: files live at the layer root, or under files/ when that directory exists. */
function rootLayer(kind, id, dir, kitDir) {
  const filesDir = exists(path.join(dir, "files")) ? path.join(dir, "files") : dir;
  const meta = readLayerMeta(dir, id, kitDir);
  return { kind, id, dir, filesDir, meta, title: meta.title ?? id };
}

export function loadLayers(manifest, kitDir) {
  const baseDir = path.join(kitDir, "skeleton/base");
  if (!exists(baseDir)) fail(`kit at ${kitDir} has no skeleton/base`);
  const layers = [rootLayer("base", "base", baseDir, kitDir)];
  const surfaces = [];
  for (const s of manifest.surfaces) {
    const dir = path.join(kitDir, "skeleton/surfaces", s);
    if (!exists(dir)) fail(`manifest.surfaces lists "${s}" but ${path.relative(kitDir, dir)} does not exist`);
    surfaces.push(rootLayer("surface", s, dir, kitDir));
  }
  checkSurfaceRequires(manifest, surfaces);
  layers.push(...surfaces);
  layers.push(...resolveModules(manifest, kitDir));
  return layers;
}

/**
 * A surface's `requires` names the surfaces (and modules) it rides on — mobile ships its
 * Appium lane inside the tests workspace web owns, so it requires web. Checked the way a
 * module's are: every missing piece is listed, and the scaffold fails with the reasons.
 */
function checkSurfaceRequires(manifest, surfaces) {
  const problems = [];
  for (const layer of surfaces) {
    for (const req of layer.meta.requires ?? []) {
      if (SURFACE_ORDER.includes(req)) {
        if (!manifest.surfaces.includes(req)) problems.push(`surface "${layer.id}" requires surface "${req}", which is not in manifest.surfaces (${manifest.surfaces.join(", ") || "none"})`);
      } else if (!manifest.modules.includes(req)) {
        problems.push(`surface "${layer.id}" requires module "${req}" — add "${req}" to manifest.modules`);
      }
    }
  }
  if (problems.length) fail(`surface dependencies are not satisfied:\n  - ${problems.join("\n  - ")}`);
}

export function resolveModules(manifest, kitDir) {
  const modulesDir = path.join(kitDir, "skeleton/modules");
  const available = exists(modulesDir)
    ? fs
        .readdirSync(modulesDir, { withFileTypes: true })
        .filter((e) => e.isDirectory() && exists(path.join(modulesDir, e.name, "module.json")))
        .map((e) => e.name)
        .sort()
    : [];
  const byId = new Map();
  for (const id of manifest.modules) {
    const dir = path.join(modulesDir, id);
    if (!exists(path.join(dir, "module.json"))) {
      fail(`manifest.modules lists "${id}" but skeleton/modules/${id}/module.json does not exist. Available: ${available.join(", ") || "(none)"}`);
    }
    const meta = readLayerMeta(dir, id, kitDir);
    byId.set(id, { kind: "module", id, dir, filesDir: path.join(dir, "files"), meta, title: meta.title ?? id });
  }
  // requires: a module may name modules or surfaces
  const problems = [];
  for (const [id, layer] of byId) {
    for (const req of layer.meta.requires ?? []) {
      if (SURFACE_ORDER.includes(req)) {
        if (!manifest.surfaces.includes(req)) problems.push(`module "${id}" requires surface "${req}", which is not in manifest.surfaces (${manifest.surfaces.join(", ") || "none"})`);
      } else if (!byId.has(req)) {
        const known = available.includes(req) ? `add "${req}" to manifest.modules` : `"${req}" is neither a known module nor a surface`;
        problems.push(`module "${id}" requires "${req}" — ${known}`);
      }
    }
  }
  if (problems.length) fail(`module dependencies are not satisfied:\n  - ${problems.join("\n  - ")}`);
  // topological order (DFS in manifest order; dependencies first); cycles are errors
  const ordered = [];
  const state = new Map(); // id → "visiting" | "done"
  const visit = (id, stack) => {
    if (state.get(id) === "done") return;
    if (state.get(id) === "visiting") fail(`module dependency cycle: ${[...stack, id].join(" → ")}`);
    state.set(id, "visiting");
    for (const req of byId.get(id).meta.requires ?? []) if (byId.has(req)) visit(req, [...stack, id]);
    state.set(id, "done");
    ordered.push(byId.get(id));
  };
  for (const id of manifest.modules) visit(id, []);
  return ordered;
}

// ───────────────────────────── file plan ─────────────────────────────
