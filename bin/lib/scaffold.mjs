/** Recursive, sorted walk. Yields { rel, abs, kind: "file"|"symlink" }. Directories are not yielded. */
export function walk(root, rel = "") {
  const dir = path.join(root, rel);
  if (!exists(dir)) return [];
  const out = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const e of entries) {
    const r = rel ? `${rel}/${e.name}` : e.name;
    const abs = path.join(root, r);
    if (e.isSymbolicLink()) out.push({ rel: r, abs, kind: "symlink" });
    else if (e.isDirectory()) out.push(...walk(root, r));
    else if (e.isFile()) out.push({ rel: r, abs, kind: "file" });
  }
  return out;
}

const utf8 = new TextDecoder("utf-8", { fatal: true });
export function isTextBuffer(buf, name) {
  if (BINARY_EXT.has(path.extname(name).toLowerCase())) return false;
  if (buf.includes(0)) return false;
  try {
    utf8.decode(buf);
    return true;
  } catch {
    return false;
  }
}

// ───────────────────────────── JSON-schema validator (subset) ─────────────────────────────
// Supports what docs/manifest.schema.json and docs/module.schema.json use: type, required, properties,
// additionalProperties, propertyNames, items, enum, const, pattern, minLength, maxLength, minItems,
// uniqueItems, minimum, $ref (#/$defs/… only).

export function validateSchema(schema, value, root = schema, at = "$", errors = []) {
  if (schema.$ref) {
    const target = schema.$ref.replace(/^#\//, "").split("/").reduce((o, k) => (o ? o[k] : undefined), root);
    if (!target) fail(`schema: unresolved $ref ${schema.$ref}`);
    return validateSchema(target, value, root, at, errors);
  }
  const typeOf = (v) => (v === null ? "null" : Array.isArray(v) ? "array" : Number.isInteger(v) ? "integer" : typeof v);
  const matches = (t, v) => (t === "number" ? typeof v === "number" : t === "integer" ? Number.isInteger(v) : typeOf(v) === t);
  if (schema.type) {
    const types = [].concat(schema.type);
    if (!types.some((t) => matches(t, value))) {
      errors.push(`${at}: expected ${types.join(" | ")}, got ${typeOf(value)}`);
      return errors;
    }
  }
  if (schema.const !== undefined && JSON.stringify(value) !== JSON.stringify(schema.const)) errors.push(`${at}: must equal ${JSON.stringify(schema.const)}`);
  if (schema.enum && !schema.enum.some((e) => JSON.stringify(e) === JSON.stringify(value))) errors.push(`${at}: must be one of ${schema.enum.map((e) => JSON.stringify(e)).join(", ")}`);
  if (typeof value === "string") {
    if (schema.minLength !== undefined && value.length < schema.minLength) errors.push(`${at}: shorter than ${schema.minLength}`);
    if (schema.maxLength !== undefined && value.length > schema.maxLength) errors.push(`${at}: longer than ${schema.maxLength}`);
    if (schema.pattern && !new RegExp(schema.pattern).test(value)) errors.push(`${at}: "${value}" does not match ${schema.pattern}`);
  }
  if (typeof value === "number" && schema.minimum !== undefined && value < schema.minimum) errors.push(`${at}: below minimum ${schema.minimum}`);
  if (Array.isArray(value)) {
    if (schema.minItems !== undefined && value.length < schema.minItems) errors.push(`${at}: fewer than ${schema.minItems} items`);
    if (schema.uniqueItems && new Set(value.map((v) => JSON.stringify(v))).size !== value.length) errors.push(`${at}: items must be unique`);
    if (schema.items) value.forEach((v, i) => validateSchema(schema.items, v, root, `${at}[${i}]`, errors));
  }
  if (isObject(value)) {
    for (const k of schema.required ?? []) if (!(k in value)) errors.push(`${at}: missing required "${k}"`);
    const props = schema.properties ?? {};
    for (const [k, v] of Object.entries(value)) {
      if (schema.propertyNames) validateSchema(schema.propertyNames, k, root, `${at} key`, errors);
      if (k in props) validateSchema(props[k], v, root, `${at}.${k}`, errors);
      else if (schema.additionalProperties === false) errors.push(`${at}: unknown key "${k}"`);
      else if (isObject(schema.additionalProperties)) validateSchema(schema.additionalProperties, v, root, `${at}.${k}`, errors);
    }
  }
  return errors;
}

