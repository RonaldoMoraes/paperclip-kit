// ── Biome-shaped JSON ──
// Every JSON file the engine writes into a product tree (package.json, biome.json, .claude/settings.json,
// the allowlist, the ledger) is linted by that tree's own Biome, so the engine prints what Biome 2.5's
// JSON formatter would (lineWidth 120, two-space indent): objects always expanded (Biome keeps an object
// expanded when its source breaks after the `{`), an array flat when its one-line form — trailing comma
// included — fits the line and holds no non-empty object, a number-only array that overflows packed
// greedily under the same rule (Biome's fill), everything else one element per line. Key order is kept.
// `package.json` is the exception: Biome formats that file name with `expand: always` — every non-empty array
// and object on its own lines, the way npm writes it — so `formatJson(v, { expand: true })` does the same.
const JSON_LINE_WIDTH = 120;
const jsonWidth = (s) => [...s].length;
// Biome prints a number literal without the `+` of its exponent (`1e21`, never `1e+21`).
const jsonLeaf = (v) => (v === undefined ? "null" : typeof v === "number" ? JSON.stringify(v).replace("e+", "e") : JSON.stringify(v));
const holdsObject = (v) => isObject(v) ? Object.keys(v).length > 0 : Array.isArray(v) && v.some(holdsObject);
const flatJson = (v) => {
  if (Array.isArray(v)) return v.length === 0 ? "[]" : `[${v.map(flatJson).join(", ")}]`;
  if (isObject(v)) return "{}"; // only an empty object reaches the flat path
  return jsonLeaf(v);
};
const fillJson = (nums, indent) => {
  const pad = " ".repeat(indent + 2);
  const out = [];
  let line = pad + jsonLeaf(nums[0]);
  for (let i = 1; i < nums.length; i += 1) {
    const item = jsonLeaf(nums[i]);
    const tail = i < nums.length - 1 ? 1 : 0;
    if (jsonWidth(line) + 2 + jsonWidth(item) + tail <= JSON_LINE_WIDTH) line += `, ${item}`;
    else {
      out.push(`${line},`);
      line = pad + item;
    }
  }
  out.push(line);
  return `[\n${out.join("\n")}\n${" ".repeat(indent)}]`;
};
/** `col` is the column the value starts at; `tail` the width of what follows it on the same line (a comma or nothing). */
const fmtJson = (v, indent, col, tail, expand) => {
  if (Array.isArray(v)) {
    if (v.length === 0) return "[]";
    if (!expand && !v.some(holdsObject)) {
      const flat = flatJson(v);
      if (col + jsonWidth(flat) + tail <= JSON_LINE_WIDTH) return flat;
    }
    if (!expand && v.every((x) => typeof x === "number")) return fillJson(v, indent);
    const pad = " ".repeat(indent + 2);
    const items = v.map((x, i) => pad + fmtJson(x, indent + 2, indent + 2, i < v.length - 1 ? 1 : 0, expand));
    return `[\n${items.join(",\n")}\n${" ".repeat(indent)}]`;
  }
  if (isObject(v)) {
    const keys = Object.keys(v).filter((k) => v[k] !== undefined);
    if (keys.length === 0) return "{}";
    const pad = " ".repeat(indent + 2);
    const members = keys.map((k, i) => {
      const prefix = `${pad}${JSON.stringify(k)}: `;
      return prefix + fmtJson(v[k], indent + 2, jsonWidth(prefix), i < keys.length - 1 ? 1 : 0, expand);
    });
    return `{\n${members.join(",\n")}\n${" ".repeat(indent)}}`;
  }
  return jsonLeaf(v);
};
