export function resolvePlaceholders(manifest, layers = []) {
  const p = manifest.product;
  const noDash = (s) => s.replace(/-/g, "");
  const map = {
    __PRODUCT_SLUG__: p.slug,
    __PRODUCT_NAME__: p.name,
    __SCOPE__: p.scope,
    __COOKIE_PREFIX__: p.cookiePrefix ?? p.slug,
    __BUNDLE_ID__: p.bundleId ?? `com.${noDash(p.scope)}.${noDash(p.slug)}`,
    __SCHEME__: p.scheme ?? p.slug,
    __DOMAIN__: p.domain ?? `${p.slug}.example.com`,
    __TRUNK__: p.trunk ?? "development",
    __DB_NAME__: p.dbName ?? p.slug.replace(/-/g, "_"),
  };
  const missing = [];
  for (const layer of layers) {
    for (const ph of layer.meta.placeholders ?? []) {
      const value = manifest.placeholders?.[ph.key] ?? ph.default;
      if (value === undefined) missing.push(`${ph.key} (${layer.id}: ${ph.question})`);
      // a value may name a placeholder resolved before it (`no-reply@__DOMAIN__`)
      else map[ph.key] = substitute(value, map);
    }
  }
  if (missing.length) fail(`manifest.placeholders is missing values the selected modules need:\n  - ${missing.join("\n  - ")}`);
  return map;
}

export function substitute(text, placeholders) {
  const keys = Object.keys(placeholders);
  if (!keys.length) return text;
  const re = new RegExp(keys.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"), "g");
  return text.replace(re, (m) => placeholders[m]);
}

/** Every string in a JSON value — keys included, so `"@__SCOPE__/db": "workspace:*"` resolves — with placeholders filled. */
export function substituteDeep(value, placeholders) {
  if (typeof value === "string") return substitute(value, placeholders);
  if (Array.isArray(value)) return value.map((v) => substituteDeep(v, placeholders));
  if (isObject(value)) return Object.fromEntries(Object.entries(value).map(([k, v]) => [substitute(k, placeholders), substituteDeep(v, placeholders)]));
  return value;
}

/**
 * A layer's manifest (module.json / surface.json) carries product-specific strings the same
 * way its files do — a workspace dependency on `@__SCOPE__/db`, a script that names
 * `__DB_NAME__`, a post-scaffold note — so once the placeholders are known the manifests are
 * filled in place, before any gen or merged file reads them.
 */
export function applyPlaceholders(layers, placeholders) {
  for (const layer of layers) {
    layer.meta = substituteDeep(layer.meta, placeholders);
    layer.title = layer.meta.title ?? layer.id;
  }
  return layers;
}

