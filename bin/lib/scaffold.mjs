export function mergeEnv(seed, fragments) {
  let out = ensureTrailingNewline(seed);
  for (const f of fragments) {
    const header = `# --- ${f.id}: ${f.title} ---`;
    if (lines(out).includes(header)) continue;
    out += `\n${header}\n${ensureTrailingNewline(f.text.trimEnd())}`;
  }
  return out;
}

export function resolveVersions(pkg, versions, label) {
  const out = clone(pkg);
  const missing = [];
  for (const key of DEP_KEYS) {
    if (!isObject(out[key])) continue;
    for (const [name, v] of Object.entries(out[key])) {
      if (v !== "@versions") continue;
      if (versions[name] === undefined) missing.push(`${name} (${label} → ${key})`);
      else out[key][name] = versions[name];
    }
  }
  if (missing.length) fail(`"@versions" has no entry in skeleton/versions.json for:\n  - ${missing.join("\n  - ")}`);
  for (const key of SORTED_DEP_KEYS) if (isObject(out[key])) out[key] = sortObject(out[key]);
  return out;
}

export function mergePackage(seed, contributions, versions, label, warn = () => {}) {
  const out = clone(seed);
  for (const { id, fragment } of contributions) {
    for (const key of Object.keys(fragment)) {
      if (!PACKAGE_MERGE_KEYS.includes(key)) {
        // any other key (e.g. msw.workerDirectory) is set only when the seed does not have it
        if (key in out) {
          if (JSON.stringify(out[key]) !== JSON.stringify(fragment[key])) warn(`${id}: packages fragment key "${key}" already exists in ${label} with a different value; left as is`);
        } else out[key] = clone(fragment[key]);
        continue;
      }
      if (key === "workspaces") out.workspaces = union(out.workspaces ?? [], fragment.workspaces);
      else out[key] = { ...(out[key] ?? {}), ...fragment[key] };
    }
  }
  return resolveVersions(out, versions, label);
}

export function mergeBiome(seed, contributions, warn = () => {}) {
  const out = clone(seed);
  for (const { plugins = [], overrides = [] } of contributions) {
    if (plugins.length) out.plugins = union(out.plugins ?? [], plugins);
    for (const o of overrides) {
      out.overrides = out.overrides ?? [];
      const key = JSON.stringify(o);
      if (out.overrides.some((x) => JSON.stringify(x) === key)) continue;
      if (out.overrides.length === 0) out.overrides.push(o);
      else out.overrides.splice(out.overrides.length - 1, 0, o);
    }
  }
  const last = out.overrides?.[out.overrides.length - 1];
  if (last && !JSON.stringify(last.includes ?? []).includes("apps/server")) warn("biome.json: the last override is not the server override; Biome takes the parser from the last matching override");
  return out;
}

export function mergeSettings(seed, hooks) {
  const out = clone(seed) ?? {};
  out.hooks = out.hooks ?? {};
  if (!Array.isArray(out.hooks.PostToolUse) || out.hooks.PostToolUse.length === 0) out.hooks.PostToolUse = [{ matcher: "Edit|Write|MultiEdit", hooks: [] }];
  const group = out.hooks.PostToolUse[0];
  group.hooks = group.hooks ?? [];
  for (const h of hooks) {
    if (group.hooks.some((x) => x.command === h.command)) continue;
    group.hooks.push({ type: "command", ...h });
  }
  return out;
}

export function mergeAllow(seed, entries) {
  const out = Array.isArray(seed) ? clone(seed) : [];
  for (const e of entries) if (!out.some((x) => JSON.stringify(x) === JSON.stringify(e))) out.push(e);
  return out;
}

/** Inserts `blocks` (each {present: (text) => boolean, text}) before the marker line; the marker stays. */
export function insertBeforeMarker(text, marker, blocks, file) {
  const ls = lines(ensureTrailingNewline(text));
  const idx = ls.findIndex((l) => l.trim() === marker);
  if (idx < 0) fail(`${file} has no "${marker}" marker line`);
  const toInsert = [];
  for (const b of blocks) if (!b.present(text)) toInsert.push(...lines(b.text.replace(/\n$/, "")));
  ls.splice(idx, 0, ...toInsert);
  return ls.join("\n");
}

export function mergeDocsReadme(seed, entries) {
  return insertBeforeMarker(
    seed,
    MARKERS.modules,
    entries.map((e) => ({ present: (t) => t.includes(`](${e.id}.md)`), text: `- [${e.title}](${e.id}.md) — ${e.summary ?? ""}`.trimEnd() })),
    MERGE_FILES.docsReadme
  );
}

/** Each module's rules live between <!-- kit:module:<id> --> markers; an existing block is refreshed in place. */
export function mergeAgents(seed, fragments) {
  let text = ensureTrailingNewline(seed);
  const blockOf = (f) => `<!-- kit:module:${f.id} -->\n${ensureTrailingNewline(f.text.trim())}<!-- /kit:module:${f.id} -->\n`;
  const pending = [];
  for (const f of fragments) {
    const open = `<!-- kit:module:${f.id} -->`;
    const close = `<!-- /kit:module:${f.id} -->`;
    const a = text.indexOf(open);
    const b = text.indexOf(close);
    if (a >= 0 && b > a) text = text.slice(0, a) + blockOf(f).replace(/\n$/, "") + text.slice(b + close.length);
    else pending.push({ present: () => false, text: blockOf(f) });
  }
  return insertBeforeMarker(text, MARKERS.rules, pending, MERGE_FILES.agents);
}

// ───────────────────────────── the scaffold ─────────────────────────────

function loadLock(outDir) {
  const p = path.join(outDir, LOCK_PATH);
  return exists(p) ? readJson(p) : null;
}

/** A fragment (.env.fragment, agents-fragment.md) is text the kit ships: placeholders are filled before the merge, as in any copied file. */
function fragmentOf(layer, name, placeholders) {
  const p = path.join(layer.filesDir, name);
  return exists(p) ? substitute(fs.readFileSync(p, "utf8"), placeholders) : null;
}

/**
 * Every .env.fragment a layer ships, each with the .env.example it merges into — the one beside it:
 * files/.env.fragment → .env.example, files/apps/mobile/.env.fragment → apps/mobile/.env.example,
 * files/tests/.env.fragment → tests/.env.example. Whether the target is in play is decided at merge time.
 */
function envFragmentsOf(layer, placeholders) {
  return walk(layer.filesDir)
    .filter((f) => f.kind === "file" && path.posix.basename(f.rel) === ENV_FRAGMENT)
    .map((f) => ({
      rel: f.rel,
      target: path.posix.join(path.posix.dirname(f.rel), MERGE_FILES.env),
      id: layer.id,
      title: layer.title,
      text: substitute(fs.readFileSync(f.abs, "utf8"), placeholders),
    }));
}

/**
 * Runs the scaffold. Returns { actions: [{rel, action, kind, source}], summary, checklist, warnings }.
 * opts: { manifestPath, outDir, kitDir, update, dryRun, forceGen, log }
 */
export function scaffold(opts) {
  const log = opts.log ?? (() => {});
  const warnings = [];
  const warn = (m) => warnings.push(m);
  const kitDir = path.resolve(opts.kitDir);
  const outDir = path.resolve(opts.outDir ?? process.cwd());
  const manifestPath = path.resolve(opts.manifestPath);
  const kitVersion = exists(path.join(kitDir, "VERSION")) ? fs.readFileSync(path.join(kitDir, "VERSION"), "utf8").trim() : "0.0.0";
  const versions = readJson(path.join(kitDir, "skeleton/versions.json")).packages ?? {};

  const manifest = loadManifest(manifestPath, kitDir);
  if (manifest.kit.version !== kitVersion) warn(`manifest was written for kit ${manifest.kit.version}; this kit is ${kitVersion}`);
  const lock = loadLock(outDir);
  if (lock && !opts.update) fail(`${LOCK_PATH} exists in ${outDir}: this tree was already scaffolded. Re-run with --update.`);
  if (opts.update && !lock) warn(`--update without ${LOCK_PATH}: every existing file is treated as product-owned and left alone`);

  const layers = loadLayers(manifest, kitDir);
  const modules = layers.filter((l) => l.kind === "module");
  const placeholders = resolvePlaceholders(manifest, layers);
  applyPlaceholders(layers, placeholders);
  const plan = buildCopyPlan(layers, manifest, placeholders);
  const nonBase = layers.filter((l) => l.kind !== "base");

  // ── merged files: seed = the kit's overlay (or the product's current file when it was edited) + contributions
  const ledger = lock?.files ?? {};
  const currentText = (rel) => {
    const abs = path.join(outDir, rel);
    return exists(abs) && fs.lstatSync(abs).isFile() ? fs.readFileSync(abs, "utf8") : null;
  };
  // A merged file is "pristine" while every version of it came from the kit seed + contributions. Once the
  // product edits it (or it was merged onto a product-owned file), it stays product-owned: later updates
  // apply contributions onto the current file instead of rebuilding it from the kit seed.
  const pristine = {};
  const productOwned = (rel) => {
    if (!opts.update) return false;
    const cur = currentText(rel);
    if (cur === null) return false;
    const led = ledger[rel];
    if (!led) return true;
    if (led.kind === "merge" && led.pristine === false) return true;
    return led.hash !== sha256(Buffer.from(cur));
  };
  const seedFor = (rel, parse) => {
    const kitSeed = plan.get(rel)?.content?.toString("utf8") ?? null;
    const owned = productOwned(rel);
    const text = owned ? currentText(rel) : kitSeed;
    if (text === null) return { seed: null, kitSeed };
    pristine[rel] = !owned;
    return { seed: parse ? JSON.parse(text) : text, kitSeed };
  };
  const setMerge = (rel, content, source = "kit") => plan.set(rel, { kind: "merge", source, content: Buffer.from(content), mode: 0o644 });
  const jsonSeed = (rel) => {
    try {
      return seedFor(rel, true);
    } catch (e) {
      fail(`${rel} is not valid JSON: ${e.message}`);
    }
  };

  // Contributions aimed at a surface that is not selected (packages.mobile without mobile, apps/mobile/.env.fragment
  // without mobile) are skipped and listed here — the same rule that keeps files/apps/mobile/** out of a web-only tree.
  const skipped = [];

  // .env.example — the root one always; any other one a layer ships a fragment beside (apps/mobile, tests, …)
  {
    const byTarget = new Map([[MERGE_FILES.env, []]]);
    for (const l of nonBase) {
      for (const f of envFragmentsOf(l, placeholders)) {
        if (!byTarget.has(f.target)) byTarget.set(f.target, []);
        byTarget.get(f.target).push(f); // layer order: surfaces, then modules in dependency order
      }
    }
    for (const [target, fragments] of byTarget) {
      const { seed } = seedFor(target, false);
      if (seed !== null) {
        setMerge(target, mergeEnv(seed, fragments));
        continue;
      }
      if (!fragments.length) continue;
      const surface = unselectedSurface(target, manifest);
      if (surface) for (const f of fragments) skipped.push(`${f.rel} for ${f.id}: ${surface} surface not selected`);
      else fail(`${fragments.map((f) => f.id).join(", ")} ship ${fragments[0].rel} but no layer provides ${target}`);
    }
  }
  // package.json targets
  for (const [target, rel] of Object.entries(PACKAGE_TARGETS)) {
    const contributions = layers.filter((l) => l.meta.packages?.[target]).map((l) => ({ id: l.id, fragment: l.meta.packages[target] }));
    const { seed } = jsonSeed(rel);
    if (seed === null) {
      const surface = unselectedSurface(rel, manifest);
      if (surface) for (const c of contributions) skipped.push(`packages.${target} for ${c.id}: ${surface} surface not selected`);
      else if (contributions.length) fail(`${contributions.map((c) => c.id).join(", ")} contribute to packages.${target} but no layer provides ${rel} (missing surface or module?)`);
      continue;
    }
    setMerge(rel, formatJson(mergePackage(seed, contributions, versions, rel, warn), { expand: true }));
  }
  // biome.json
  {
    const contributions = layers.filter((l) => l.meta.biome).map((l) => l.meta.biome);
    const { seed } = jsonSeed(MERGE_FILES.biome);
    if (seed !== null) setMerge(MERGE_FILES.biome, stableJson(mergeBiome(seed, contributions, warn)));
    else if (contributions.length) fail(`modules contribute biome plugins/overrides but no layer provides ${MERGE_FILES.biome}`);
  }
  // .claude/settings.json
  {
    const hooks = layers.flatMap((l) => l.meta.hooks ?? []);
    const { seed } = jsonSeed(MERGE_FILES.settings);
    if (seed !== null || hooks.length) setMerge(MERGE_FILES.settings, stableJson(mergeSettings(seed ?? {}, hooks)));
  }
  // scripts/test-contract.allow.json
  {
    const entries = layers.flatMap((l) => l.meta.testContractAllow ?? []);
    const { seed } = jsonSeed(MERGE_FILES.allow);
    if (seed !== null || entries.length) setMerge(MERGE_FILES.allow, stableJson(mergeAllow(seed ?? [], entries)));
  }
  // docs/README.md
  {
    const entries = modules.filter((l) => l.meta.docs).map((l) => ({ id: l.id, title: l.title, summary: l.meta.summary }));
    const { seed } = seedFor(MERGE_FILES.docsReadme, false);
    if (seed !== null) setMerge(MERGE_FILES.docsReadme, mergeDocsReadme(seed, entries));
    else if (entries.length) fail(`modules declare docs but no layer provides ${MERGE_FILES.docsReadme}`);
  }
  // AGENTS.md
  {
    const fragments = nonBase.map((l) => ({ id: l.id, text: fragmentOf(l, AGENTS_FRAGMENT, placeholders) })).filter((f) => f.text !== null);
    const { seed } = seedFor(MERGE_FILES.agents, false);
    if (seed !== null) setMerge(MERGE_FILES.agents, mergeAgents(seed, fragments));
    else if (fragments.length) fail(`modules ship agents-fragment.md but no layer provides ${MERGE_FILES.agents}`);
  }

  // ── gen files
  const setGen = (rel, content) => plan.set(rel, { kind: "gen", source: "kit", content: Buffer.from(content), mode: 0o644 });
  setGen(GEN_FILES.server, genServer(layers));
  setGen(GEN_FILES.mocks, genMocks(layers));
  for (const s of manifest.surfaces) setGen(GEN_FILES[s], genSurface(layers, s));
  {
    const kitSeedText = plan.get(GEN_FILES.canaries)?.content?.toString("utf8");
    let seed = null;
    if (kitSeedText !== undefined) {
      try {
        seed = JSON.parse(kitSeedText);
      } catch (e) {
        fail(`${GEN_FILES.canaries} from the skeleton is not valid JSON: ${e.message}`);
      }
    }
    setGen(GEN_FILES.canaries, genCanaries(seed, layers));
  }

  // ── engineering layer → .agents/* with .claude/* symlinks
  for (const d of ENGINEERING_DIRS) {
    const src = path.join(kitDir, "engineering", d);
    for (const f of walk(src)) {
      if (f.kind !== "file") continue;
      const raw = fs.readFileSync(f.abs);
      const content = isTextBuffer(raw, f.rel) ? Buffer.from(substitute(raw.toString("utf8"), placeholders)) : raw;
      plan.set(`.agents/${d}/${f.rel}`, { kind: "engineering", source: "engineering", content, mode: fs.statSync(f.abs).mode & 0o777 });
    }
    if (exists(src)) {
      for (const name of fs.readdirSync(src).sort()) {
        if (name.startsWith(".")) continue;
        plan.set(`.claude/${d}/${name}`, { kind: "symlink", source: "engineering", target: `../../.agents/${d}/${name}` });
      }
    }
  }
  // CLAUDE.md → AGENTS.md
  if (plan.has("AGENTS.md") && !plan.has("CLAUDE.md")) plan.set("CLAUDE.md", { kind: "symlink", source: "base", target: "AGENTS.md" });
  // the manifest travels with the product
  if (manifestPath !== path.join(outDir, MANIFEST_DEST)) plan.set(MANIFEST_DEST, { kind: "manifest", source: "manifest", content: fs.readFileSync(manifestPath), mode: 0o644 });

  // ── decide + apply
  const actions = [];
  const newLedger = {};
  const decide = (rel, entry) => {
    const abs = path.join(outDir, rel);
    const there = exists(abs);
    if (entry.kind === "symlink") {
      if (!there) return "add";
      // A correct link is left alone silently; a real file (an older install.sh, a hand copy) is a
      // second, divergent copy of a file .agents/ already owns — never overwritten, always reported.
      return linksTo(abs, entry.target) ? "kept" : "shadowed";
    }
    if (entry.kind === "manifest") return there ? "kept" : "add";
    if (!there) return "add";
    if (!opts.update) return "overwrite";
    if (VENDOR_GENERATED.has(rel)) return "vendor";
    const cur = fs.lstatSync(abs).isFile() ? fs.readFileSync(abs) : null;
    if (cur === null) return "skip-exists";
    const same = cur.equals(entry.content);
    const led = ledger[rel];
    const untouched = led ? led.hash === sha256(cur) : false;
    if (entry.kind === "gen") {
      if (same) return "unchanged";
      return untouched || !led || opts.forceGen ? "regenerate" : "skip-edited-gen";
    }
    if (entry.kind === "merge") return same ? "unchanged" : "merge";
    if (!led) return "skip-exists";
    if (!untouched) return "skip-edited";
    return same ? "unchanged" : "update";
  };
  const writes = new Set(["add", "overwrite", "regenerate", "merge", "update"]);
  for (const rel of [...plan.keys()].sort()) {
    const entry = plan.get(rel);
    const action = decide(rel, entry);
    actions.push({ rel, action, kind: entry.kind, source: entry.source });
    const abs = path.join(outDir, rel);
    if (writes.has(action) && !opts.dryRun) {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      if (entry.kind === "symlink") fs.symlinkSync(entry.target, abs);
      else fs.writeFileSync(abs, entry.content, { mode: entry.mode ?? 0o644 });
    }
    if (entry.kind === "symlink" || entry.kind === "manifest") continue;
    if (writes.has(action) || action === "unchanged") {
      newLedger[rel] = { hash: sha256(entry.content), kind: entry.kind, source: entry.source };
      if (entry.kind === "merge") newLedger[rel].pristine = pristine[rel] ?? true;
    } else if (ledger[rel]) newLedger[rel] = ledger[rel];
  }

  const removedModules = (lock?.modules ?? []).filter((id) => !manifest.modules.includes(id));
  if (removedModules.length) warn(`modules in the lock but not in the manifest (their files are left in place): ${removedModules.join(", ")}`);

  const now = new Date().toISOString();
  const lockOut = {
    kitVersion,
    manifestHash: sha256(Buffer.from(JSON.stringify(manifest))),
    surfaces: manifest.surfaces,
    modules: modules.map((m) => m.id),
    scaffoldedAt: lock?.scaffoldedAt ?? now,
    updatedAt: now,
    files: sortObject(newLedger),
  };
  if (!opts.dryRun) {
    fs.mkdirSync(path.join(outDir, path.dirname(LOCK_PATH)), { recursive: true });
    fs.writeFileSync(path.join(outDir, LOCK_PATH), stableJson(lockOut));
  }

  const summary = {};
  for (const a of actions) summary[a.action] = (summary[a.action] ?? 0) + 1;
  const web = manifest.surfaces.includes("web");
  const hasDb = [...plan.keys()].some((rel) => rel.startsWith("db/")); // a db workspace in the tree needs its generated client
  const checklist = [
    "HUSKY=0 yarn install",
    ...(web ? ["yarn routes:generate"] : []),
    ...(hasDb ? ["yarn db:generate"] : []),
    ...nonBase.flatMap((l) => (l.meta.postScaffold ?? []).map((n) => `[${l.id}] ${n}`)),
    `gates: ${[...GATES, ...(web ? WEB_GATES : [])].map((g) => `yarn ${g}`).join(" · ")}`,
  ];
  const result = { manifest, layers, placeholders, actions, summary, checklist, warnings, skipped, lock: lockOut, outDir, kitDir };
  log(result);
  return result;
}

// ───────────────────────────── CLI ─────────────────────────────

const USAGE = `paperclip-kit scaffold — manifest → product tree

usage: scaffold.sh --manifest <path> [--out <dir>] [--kit <dir>] [--update] [--dry-run] [--force-gen]

  --manifest <path>  .paperclip/project.manifest.json (required)
  --out <dir>        where the product tree goes (default: cwd)
  --kit <dir>        the kit to read from (default: the kit containing this script)
  --update           re-apply the manifest to an existing tree: gen + merged files are regenerated,
                     untouched kit files are refreshed, product edits are never clobbered
  --dry-run          print the plan, write nothing
  --force-gen        rewrite gen files even when they were edited after the scaffold
`;

export function parseArgs(argv) {
  const opts = { update: false, dryRun: false, forceGen: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => {
      if (i + 1 >= argv.length) fail(`${a} needs a value`);
      return argv[++i];
    };
    if (a === "--manifest") opts.manifestPath = next();
    else if (a === "--out") opts.outDir = next();
    else if (a === "--kit") opts.kitDir = next();
    else if (a === "--update") opts.update = true;
    else if (a === "--dry-run") opts.dryRun = true;
    else if (a === "--force-gen") opts.forceGen = true;
    else if (a === "-h" || a === "--help") opts.help = true;
    else fail(`unknown argument ${a}\n\n${USAGE}`);
  }
  return opts;
}

const ACTION_LABEL = {
  add: "added",
  overwrite: "overwritten",
  update: "updated (kit newer, untouched since scaffold)",
  regenerate: "regenerated (gen)",
  merge: "merged",
  unchanged: "unchanged",
  kept: "kept (symlink or manifest already present)",
  vendor: "left to its toolchain (generated vendor file)",
  shadowed: "shadowed (a real file where a .claude → .agents symlink belongs)",
  "skip-exists": "skipped (exists, not kit-owned)",
  "skip-edited": "skipped (edited by the product)",
  "skip-edited-gen": "skipped gen (edited; use --force-gen)",
};

export function printReport(result, { dryRun, update }) {
  const out = [];
  const p = (s = "") => out.push(s);
  p(`${dryRun ? "[dry-run] " : ""}${update ? "update" : "scaffold"} → ${result.outDir}`);
  p(`  product ${result.manifest.product.slug} · surfaces ${result.manifest.surfaces.join(", ") || "none"} · modules ${result.layers.filter((l) => l.kind === "module").map((l) => l.id).join(", ") || "none"}`);
  p();
  if (dryRun) {
    for (const a of result.actions) p(`  ${a.action.padEnd(16)} ${a.rel}  (${a.source})`);
    p();
  }
  p("  summary");
  for (const [action, label] of Object.entries(ACTION_LABEL)) if (result.summary[action]) p(`    ${String(result.summary[action]).padStart(5)}  ${label}`);
  const listed = result.actions.filter((a) => a.action === "skip-edited" || a.action === "skip-edited-gen");
  if (listed.length) {
    p();
    p("  left alone (product edits):");
    for (const a of listed) p(`    ${a.rel}${a.action === "skip-edited-gen" ? "  ← gen file edited; --force-gen rewrites it" : ""}`);
  }
  const shadowed = result.actions.filter((a) => a.action === "shadowed");
  if (shadowed.length) {
    p();
    p("  divergent copies (.agents/ is the source of truth; delete these and re-run so .claude/ links to it):");
    for (const a of shadowed) p(`    ${a.rel}`);
  }
  if (result.skipped.length) {
    p();
    p("  skipped (surface not selected):");
    for (const s of result.skipped) p(`    ${s}`);
  }
  if (result.warnings.length) {
    p();
    p("  warnings");
    for (const w of result.warnings) p(`    ! ${w}`);
  }
  p();
  p(`  next (Claude runs these${dryRun ? " after a real run" : ""}):`);
  result.checklist.forEach((c, i) => p(`    ${i + 1}. ${c}`));
  return `${out.join("\n")}\n`;
}

export function main(argv = process.argv.slice(2)) {
  const opts = parseArgs(argv);
  if (opts.help) {
    process.stdout.write(USAGE);
    return 0;
  }
  if (!opts.manifestPath) fail(`--manifest is required\n\n${USAGE}`);
  const here = path.dirname(fileURLToPath(import.meta.url));
  opts.kitDir = opts.kitDir ?? path.resolve(here, "../..");
  const result = scaffold(opts);
  process.stdout.write(printReport(result, opts));
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    process.exitCode = main();
  } catch (e) {
    if (e instanceof ScaffoldError) {
      process.stderr.write(`✗ ${e.message}\n`);
      process.exitCode = 1;
    } else throw e;
  }
}
