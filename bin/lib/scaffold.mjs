/** The import path's last meaningful segment, camelised: `./auth` → auth, `~/features/account/index` → account. */
const lastSegment = (importPath) => {
  const parts = importPath.split("/").filter((s) => s && s !== "." && s !== ".." && s !== "~" && s !== "index");
  return camel(parts[parts.length - 1] ?? "");
};

/**
 * The one import builder every gen slot uses (server modules and ports, contract handlers, web and
 * mobile providers/gates/boot/settingsActions): {import, symbol, owner} refs → sorted import lines
 * plus `nameOf(ref)`, the local name to write into the array literal.
 *
 * A local name is unique per (owner, import path), so one module may bring the same symbol from two
 * of its own files (`handlers` from `./auth` and from `./account`). A symbol that arrives from
 * exactly one place keeps its own name and reserves it; anything else is aliased — by owner when the
 * owners differ, then by the import path's last segment when one owner brings it from two paths,
 * then by index. Whatever the manifests say, no two emitted local names are ever equal.
 */
export function buildImports(refs) {
  const keyOf = (r) => `${r.owner}\u0000${r.import}\u0000${r.symbol}`;
  // distinct (owner, import, symbol) triples in first-appearance order, grouped by symbol
  const groups = new Map();
  const seen = new Set();
  for (const r of refs) {
    const key = keyOf(r);
    if (seen.has(key)) continue;
    seen.add(key);
    groups.set(r.symbol, [...(groups.get(r.symbol) ?? []), { key, owner: r.owner, import: r.import, symbol: r.symbol }]);
  }
  const names = new Map();
  const used = new Set();
  const take = (base) => {
    let name = base;
    for (let n = 2; used.has(name); n += 1) name = `${base}_${n}`;
    used.add(name);
    return name;
  };
  // pass 1: a symbol imported from exactly one place keeps its own name — and reserves it
  for (const [symbol, list] of groups) if (list.length === 1) names.set(list[0].key, take(symbol));
  // pass 2: the rest are aliased, then made unique against every name already taken
  for (const [symbol, list] of groups) {
    if (list.length === 1) continue;
    const oneOwner = new Set(list.map((e) => e.owner)).size === 1;
    for (const e of list) {
      const byOwner = oneOwner ? symbol : `${symbol}_${camel(e.owner)}`;
      const seg = list.filter((x) => x.owner === e.owner).length > 1 ? lastSegment(e.import) : "";
      names.set(e.key, take(seg ? `${byOwner}_${seg}` : byOwner));
    }
  }
  const byPath = new Map();
  for (const list of groups.values()) {
    for (const e of list) {
      const name = names.get(e.key);
      const spec = name === e.symbol ? e.symbol : `${e.symbol} as ${name}`;
      byPath.set(e.import, union(byPath.get(e.import) ?? [], [spec]));
    }
  }
  const importLines = [...byPath.keys()].sort().map((p) => `import { ${byPath.get(p).sort().join(", ")} } from "${p}";`);
  return { importLines, nameOf: (r) => names.get(keyOf(r)) };
}

const arrayLiteral = (items) => {
  const oneLine = `[${items.join(", ")}]`;
  return oneLine.length <= 100 ? oneLine : `[\n${items.map((i) => `  ${i},`).join("\n")}\n]`;
};

const refsOf = (layers, pick) => layers.flatMap((l) => (pick(l.meta) ?? []).map((r) => ({ ...r, owner: l.id })));

/**
 * The port set. Any layer DECLARES a port together with the default provider that stands in until
 * someone claims it (`server.portDefaults`) — that is how one layer offers an extension point to
 * another. Any layer CLAIMS a declared port with a real provider (`server.ports`); the claimant
 * `requires` the declaring module, so the declaration is always in the tree. Base's three ports are
 * declared by the engine (BASE_PORT_DEFAULTS).
 *
 * A port is declared once and claimed at most once. Emission order is declaration order — base's
 * three, then the ports layers declare, in layer (dependency) order — so KIT_PORTS is stable.
 */
export function resolvePorts(layers) {
  const declared = new Map();
  for (const [port, ref] of Object.entries(BASE_PORT_DEFAULTS)) declared.set(port, { by: "base", ref });
  for (const layer of layers) {
    for (const [port, ref] of Object.entries(layer.meta.server?.portDefaults ?? {})) {
      const prev = declared.get(port);
      if (prev) fail(`port "${port}" is declared by more than one layer: ${prev.by}, ${layer.id} — a port is declared once, by the layer that owns its token and interface; claim it with server.ports instead`);
      declared.set(port, { by: layer.id, ref });
    }
  }
  const claimed = new Map();
  const undeclared = [];
  for (const layer of layers) {
    for (const [port, ref] of Object.entries(layer.meta.server?.ports ?? {})) {
      if (!declared.has(port)) {
        undeclared.push(`${layer.kind} "${layer.id}" claims port "${port}", which no layer declares`);
        continue;
      }
      const prev = claimed.get(port);
      if (prev) fail(`port "${port}" is claimed by more than one module: ${prev.by}, ${layer.id}`);
      claimed.set(port, { by: layer.id, ref });
    }
  }
  if (undeclared.length) {
    fail(`a claimed port is never declared:\n  - ${undeclared.join("\n  - ")}\ndeclared ports: ${[...declared.keys()].join(", ")} — a layer declares one with server.portDefaults`);
  }
  return [...declared].map(([port, d]) => {
    const claim = claimed.get(port);
    return { port, ...(claim ? claim.ref : d.ref), owner: claim ? claim.by : d.by };
  });
}

export function genServer(layers) {
  const modules = refsOf(layers, (m) => m.server?.modules);
  const ports = resolvePorts(layers);
  const rawBody = layers.flatMap((l) => l.meta.server?.rawBodyPaths ?? []).filter((p, i, a) => a.indexOf(p) === i);
  const { importLines, nameOf } = buildImports([...modules, ...ports]);
  return [
    GEN_HEADER,
    'import type { Provider, Type } from "@nestjs/common";',
    ...importLines,
    "",
    `export const KIT_MODULES: Type[] = ${arrayLiteral(modules.map(nameOf))};`,
    `export const KIT_PORTS: Provider[] = ${arrayLiteral(ports.map(nameOf))};`,
    `export const KIT_RAW_BODY_PATHS: string[] = ${arrayLiteral(rawBody.map((p) => JSON.stringify(p)))};`,
    "",
  ].join("\n");
}

export function genMocks(layers) {
  const handlers = refsOf(layers, (m) => m.contracts?.handlers);
  const { importLines, nameOf } = buildImports(handlers);
  return [
    GEN_HEADER,
    'import type { RequestHandler } from "msw";',
    ...importLines,
    "",
    `export const KIT_HANDLERS: RequestHandler[] = ${arrayLiteral(handlers.map((h) => `...${nameOf(h)}`))};`,
    "",
  ].join("\n");
}

export function genSurface(layers, surface) {
  const typesImport = surface === "web" ? "~/app/kit.types" : "~/kit.types";
  const providers = refsOf(layers, (m) => m[surface]?.providers);
  const gates = refsOf(layers, (m) => m[surface]?.gates);
  const boot = refsOf(layers, (m) => m[surface]?.boot);
  const actions = refsOf(layers, (m) => m[surface]?.settingsActions);
  const { importLines, nameOf } = buildImports([...providers, ...gates, ...boot, ...actions]);
  return [
    GEN_HEADER,
    `import type { Boot, Gate, Provider, SettingsAction } from "${typesImport}";`,
    ...importLines,
    "",
    `export const KIT_PROVIDERS: Provider[] = ${arrayLiteral(providers.map(nameOf))};`,
    `export const KIT_GATES: Gate[] = ${arrayLiteral(gates.map(nameOf))};`,
    `export const KIT_BOOT: Boot[] = ${arrayLiteral(boot.map(nameOf))};`,
    `export const KIT_SETTINGS_ACTIONS: SettingsAction[] = ${arrayLiteral(actions.map((a) => `...${nameOf(a)}`))};`,
    "",
  ].join("\n");
}

export function genCanaries(seed, layers) {
  const seedList = Array.isArray(seed) ? seed : Array.isArray(seed?.canaries) ? seed.canaries : [];
  const out = [];
  const seen = new Set();
  for (const c of [...seedList, ...layers.flatMap((l) => l.meta.canaries ?? [])]) {
    const key = JSON.stringify(c);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(c);
  }
  // A plain array: scripts/check-lint-guards.mjs iterates the file directly, so no header key is possible.
  return stableJson(out);
}

